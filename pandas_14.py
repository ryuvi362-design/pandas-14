import pandas as pd
import numpy as np

ipl_df = pd.read_csv("/content/matches_data.csv")

print(ipl_df.head())

ipl_df = ipl_df.dropna(subset=["winner"])
ipl_df = ipl_df.reset_index(drop=True)
print(ipl_df.head())
print("Total rows:", len(ipl_df))

conditions = [
    ipl_df["win_by_runs"] > 0,
    ipl_df["win_by_wickets"] > 0
]

choices = ["Runs", "Wickets"]

ipl_df["match_margin_type"] = np.select(
    conditions,
    choices,
    default="Tie/No Result"
)

print(ipl_df[[
    "winner", "win_by_runs", "win_by_wickets",
    "match_margin_type"
]].head(10))

team_city = pd.DataFrame({
    "team": [
        "Mumbai Indians",
        "Chennai Super Kings",
        "Royal Challengers Bangalore",
        "Kolkata Knight Riders",
        "Rajasthan Royals",
        "Sunrisers Hyderabad",
        "Delhi Capitals",
        "Punjab Kings",
        "Gujarat Titans",
        "Lucknow Super Giants"
    ],
    "home_city": [
        "Mumbai",
        "Chennai",
        "Bengaluru",
        "Kolkata",
        "Jaipur",
        "Hyderabad",
        "Delhi",
        "Mohali",
        "Ahmedabad",
        "Lucknow"
    ]
})

team1_city = team_city.rename(columns={
    "team": "team1",
    "home_city": "team1_home_city"
})

ipl_df = pd.merge(ipl_df, team1_city, on="team1", how="left")

team2_city = team_city.rename(columns={
    "team": "team2",
    "home_city": "team2_home_city"
})

ipl_df = pd.merge(ipl_df, team2_city, on="team2", how="left")

print(ipl_df[[
    "team1", "team1_home_city",
    "team2", "team2_home_city"
]].head(10))

ipl_df["match_count"]
pivot_table = pd.pivot_table(
    ipl_df,
    index="season",
    columns="winner",
    values="match_count",
    aggfunc="sum",
    fill_value=0
)

print("Matches won by each team per season:")
print(pivot_table)

# Find the top 3 team-season combinations
team_season_wins = (
    ipl_df.groupby(["season", "winner"])
    .size()
    .reset_index(name="total_wins")
)

top_3 = team_season_wins.sort_values(
    by="total_wins",
    ascending=False
).head(3)

print("\nTop 3 team-season combinations:")
print(top_3)